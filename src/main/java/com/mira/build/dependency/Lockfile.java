package com.mira.build.dependency;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import com.mira.lib.std.TomlParser;

/**
 * Reads/writes mira.lock: pins each git dependency to the exact commit that was
 * resolved for it, so repeat builds reuse the cache instead of re-resolving
 * "tag"/"version" constraints against the remote every time.
 */
public final class Lockfile {

    public record Entry(String name, String url, String resolved, String commit) {

    }

    private Lockfile() {
    }

    public static Map<String, Entry> read(Path lockPath) {
        Map<String, Entry> entries = new LinkedHashMap<>();
        if (!Files.exists(lockPath)) {
            return entries;
        }
        try {
            String content = Files.readString(lockPath);
            Map<String, Object> root = TomlParser.parse(content);
            Object packages = root.get("package");
            if (packages instanceof List<?> list) {
                for (Object item : list) {
                    if (item instanceof Map<?, ?> pkg) {
                        String name = (String) pkg.get("name");
                        String url = (String) pkg.get("url");
                        String resolved = (String) pkg.get("resolved");
                        String commit = (String) pkg.get("commit");
                        if (name != null && url != null && commit != null) {
                            entries.put(name, new Entry(name, url, resolved, commit));
                        }
                    }
                }
            }
        } catch (IOException e) {
            throw new UncheckedIOException("Failed to read " + lockPath, e);
        }
        return entries;
    }

    public static void write(Path lockPath, Map<String, Entry> entries) {
        List<String> names = new ArrayList<>(entries.keySet());
        names.sort(String::compareTo);

        StringBuilder sb = new StringBuilder();
        sb.append("# This file is auto-generated by mira. Do not edit by hand.\n");
        for (String name : names) {
            Entry e = entries.get(name);
            sb.append("\n[[package]]\n");
            sb.append("name = \"").append(escape(e.name())).append("\"\n");
            sb.append("url = \"").append(escape(e.url())).append("\"\n");
            if (e.resolved() != null) {
                sb.append("resolved = \"").append(escape(e.resolved())).append("\"\n");
            }
            sb.append("commit = \"").append(escape(e.commit())).append("\"\n");
        }
        try {
            Files.writeString(lockPath, sb.toString());
        } catch (IOException e) {
            throw new UncheckedIOException("Failed to write " + lockPath, e);
        }
    }

    private static String escape(String s) {
        return s.replace("\\", "\\\\").replace("\"", "\\\"");
    }
}
